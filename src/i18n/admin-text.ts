export const adminTexts: Record<Locale, AdminText> = { km, en };

/** Map an ActionResult error code to a message. */
export function errorMessage(code: string, t: AdminText): string {
  if (code.startsWith("DUPLICATE_PHONE")) return t.errors.DUPLICATE_PHONE;
  if (code.startsWith("DUPLICATE")) return t.errors.DUPLICATE;
  if (code === "FORBIDDEN" || code.startsWith("FORBIDDEN")) return t.errors.FORBIDDEN;
  return (t.errors as Record<string, string>)[code] ?? code;
}
